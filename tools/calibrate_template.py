#!/usr/bin/env python3
"""
calibrate_template.py
----------------------
Run this ONCE per new vendor/invoice layout (not per invoice) to generate a
template.json like config/template_bharat_associates.json.

Usage (needs a local display -- run this on your own machine, not a headless
server/sandbox):

    python tools/calibrate_template.py --image path/to/one_blank_or_filled_sample.jpg \
                                        --out config/template_myvendor.json

For each field it opens a window on the reference image and asks you to drag
a rectangle around that field, then press ENTER/SPACE to confirm (or 'c' to
skip a field that doesn't apply on this layout, e.g. no consignee line).

Tips for accurate calibration:
  - Use a sample where the printed grid lines are clearly visible.
  - Draw boxes slightly LARGER than the text to allow for handwriting that
    overflows the printed line.
  - For "items_table", first draw a box around the WHOLE table (header row
    to last ruled row), then you'll be asked to drag each column's box
    inside a zoomed view of just that table -- draw column boundaries at
    the printed vertical rule lines.
"""

import argparse
import json
import os

import cv2

SIMPLE_FIELDS = [
    ("buyer_name", "trocr", "text"),
    ("buyer_address_l1", "trocr", "text"),
    ("buyer_address_l2", "trocr", "text"),
    ("buyer_state", "trocr", "text"),
    ("buyer_gstin", "trocr", "gstin"),
    ("invoice_no", "trocr", "text"),
    ("invoice_date", "trocr", "date"),
    ("electronic_ref", "trocr", "text"),
    ("consignee_address", "trocr", "text"),
    ("amount_in_words", "trocr", "text"),
    ("total_before_gst", "trocr", "amount"),
    ("cgst_pct", "trocr", "percent"),
    ("cgst_amount", "trocr", "amount"),
    ("sgst_pct", "trocr", "percent"),
    ("sgst_amount", "trocr", "amount"),
    ("igst_pct", "trocr", "percent"),
    ("igst_amount", "trocr", "amount"),
    ("total_after_tax", "trocr", "amount"),
    ("reverse_charge_mark", "trocr", "text"),
]

TABLE_COLUMNS = ["sno", "description", "hsn", "rate", "taxable_value"]

STATIC_FIELD_PROMPTS = [
    "supplier_name", "supplier_address", "supplier_gstin", "supplier_phone",
    "bank_name", "bank_account_no", "bank_branch", "bank_ifsc",
]


def select_box(img, window_title):
    print(f"\n>>> Drag a box for: {window_title}   (ENTER/SPACE=confirm, c=skip this field)")
    r = cv2.selectROI(window_title, img, showCrosshair=True, fromCenter=False)
    cv2.destroyWindow(window_title)
    x, y, w, h = r
    if w == 0 or h == 0:
        return None
    return (x, y, x + w, y + h)


def normalize(box, w, h):
    x0, y0, x1, y1 = box
    return [round(x0 / w, 5), round(y0 / h, 5), round(x1 / w, 5), round(y1 / h, 5)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--image", required=True, help="One representative sample of the new invoice layout.")
    ap.add_argument("--out", required=True, help="Where to save the generated template.json")
    ap.add_argument("--template-name", default="New Vendor Template")
    args = ap.parse_args()

    img = cv2.imread(args.image)
    if img is None:
        raise SystemExit(f"Could not read image: {args.image}")
    h, w = img.shape[:2]

    regions = {}
    for name, engine, ftype in SIMPLE_FIELDS:
        box = select_box(img, name)
        if box is None:
            print(f"  skipped {name}")
            continue
        regions[name] = {"box": normalize(box, w, h), "engine": engine, "type": ftype}

    print("\n>>> Now draw a box around the WHOLE items table (header to bottom rule).")
    table_box = select_box(img, "items_table (whole table)")
    if table_box is not None:
        tx0, ty0, tx1, ty1 = table_box
        table_crop = img[ty0:ty1, tx0:tx1]
        th, tw = table_crop.shape[:2]
        columns = {}
        for col in TABLE_COLUMNS:
            cbox = select_box(table_crop, f"column: {col}")
            if cbox is None:
                continue
            cx0, cy0, cx1, cy1 = cbox
            # store as fractions of the TABLE's own width (matches row_segmentation's expectation)
            columns[col] = [round(cx0 / tw, 5), round(cx1 / tw, 5)]
        regions["items_table"] = {
            "box": normalize(table_box, w, h),
            "engine": "trocr",
            "type": "table",
            "columns": columns,
        }

    print("\n>>> Now type the vendor's FIXED printed details (press Enter to leave blank).")
    static_fields = {}
    for key in STATIC_FIELD_PROMPTS:
        val = input(f"  {key}: ").strip()
        if val:
            static_fields[key] = val

    template = {
        "template_name": args.template_name,
        "description": "Generated by tools/calibrate_template.py",
        "reference_image_size": {"width": w, "height": h},
        "static_fields": static_fields,
        "regions": regions,
    }

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        json.dump(template, f, indent=2)
    print(f"\nSaved template to {args.out}")
    print("Run main.py with --template pointing at this file to use it.")


if __name__ == "__main__":
    main()
